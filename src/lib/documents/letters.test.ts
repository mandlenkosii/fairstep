import { describe, expect, it } from "vitest";
import type { WorkflowCase } from "@/lib/workflow/types";
import { buildLetter, documentReadiness, type LetterInput } from "./letters";

const NOW = new Date("2026-11-23T08:00:00Z");

const kase: WorkflowCase = {
  currentStep: "notice",
  incidentOccurredAt: "2026-11-09T19:30:00Z",
  people: {
    complainant: "Lerato Khumalo",
    investigator: "Thabo Mokoena",
    chairperson: "Naledi Dlamini",
    witnesses: ["Ayanda Zulu"],
  },
  investigation: { findings: "CCTV shows the drawer open." },
  notice: {
    allegations: ["Negligence: leaving the cash drawer open on 9 Nov 2026."],
    deliveredAt: "2026-11-23T08:00:00Z",
    hearingAt: "2026-11-26T08:00:00Z",
    venue: "Back office, Kasi Kitchen",
    rights: { representation: true, interpreter: true, witnesses: true },
  },
  hearing: { employeeAttended: true, employeeResponse: "I forgot to lock it.", postponements: 0 },
  outcome: {
    sanction: "written",
    reasons: "First offence; admitted.",
    deliveredAt: "2026-11-27T10:00:00Z",
    priorWarnings: [],
  },
};

const input = (c: WorkflowCase = kase): LetterInput => ({
  business: { name: "Kasi Kitchen" },
  employee: { name: "Bongani Mthembu", jobTitle: "Cashier", number: "KK-004" },
  reference: "FS-2026-0002",
  issuedBy: "Thabo Mokoena",
  workflow: c,
  generatedAt: NOW,
});

describe("documentReadiness", () => {
  it("allows a notice when R2–R5 pass", () => {
    expect(documentReadiness(kase, "notice", NOW)).toEqual({ ok: true });
  });

  it("allows a notice before it's delivered, counting notice from today", () => {
    const notice = { ...kase.notice!, deliveredAt: undefined };
    expect(documentReadiness({ ...kase, notice }, "notice", NOW)).toEqual({ ok: true });
  });

  it("blocks a notice without findings (R2) or with a partial chair (R5)", () => {
    const result = documentReadiness(
      { ...kase, investigation: {}, people: { ...kase.people, chairperson: "Lerato Khumalo" } },
      "notice",
      NOW,
    );
    expect(result.ok).toBe(false);
    expect(!result.ok && result.reasons).toEqual([
      "Record what you found in your investigation first, so the allegations are clear.",
      "The chairperson can't also be the complainant. Choose someone who wasn't involved.",
    ]);
  });

  it("only allows the warning letter that matches the outcome", () => {
    expect(documentReadiness(kase, "warning", NOW)).toEqual({ ok: true });
    expect(documentReadiness(kase, "final_warning", NOW)).toEqual({
      ok: false,
      reasons: ["The recorded outcome isn't a final written warning."],
    });
  });

  it("blocks an outcome letter for a dismissal without reasons (R8)", () => {
    const outcome = { ...kase.outcome!, sanction: "dismissal" as const, reasons: "" };
    const result = documentReadiness({ ...kase, outcome }, "outcome", NOW);
    expect(!result.ok && result.reasons).toEqual([
      "Explain why dismissal is appropriate, including any prior valid warnings.",
    ]);
  });

  it("blocks outcome letters before an outcome is recorded", () => {
    const result = documentReadiness({ ...kase, outcome: undefined }, "outcome", NOW);
    expect(!result.ok && result.reasons).toEqual(["Record the outcome of the hearing first."]);
  });
});

describe("buildLetter: notice of hearing", () => {
  const letter = buildLetter("notice", input());

  it("is addressed to the employee with the case reference", () => {
    expect(letter.title).toBe("Notice to attend a disciplinary hearing");
    expect(letter.to).toBe("Bongani Mthembu, Cashier (KK-004)");
    expect(letter.reference).toBe("FS-2026-0002");
    expect(letter.date).toBe("23 November 2026");
  });

  it("states when and where the hearing is, in SAST", () => {
    expect(letter.lead).toBe(
      "You are required to attend a disciplinary hearing on Thursday 26 November 2026 at 10:00, at Back office, Kasi Kitchen.",
    );
  });

  it("lists the allegations and the rights given", () => {
    expect(letter.sections[0]).toEqual({
      heading: "Allegations",
      bullets: kase.notice!.allegations,
    });
    expect(letter.sections[1].heading).toBe("Your rights");
    expect(letter.sections[1].bullets).toHaveLength(4);
  });

  it("carries the signature lines and the not-legal-advice footer", () => {
    expect(letter.signatures).toEqual([
      "Issued by Thabo Mokoena",
      "Received by employee: signature and date",
    ]);
    expect(letter.footer).toBe(
      "Generated by FairStep on 23 Nov 2026 at 10:00 SAST. FairStep guides process and keeps records. It is not legal advice.",
    );
  });
});

describe("buildLetter: warnings and outcome", () => {
  it("says how long a written warning stays valid and how to appeal", () => {
    const letter = buildLetter("warning", input());
    expect(letter.title).toBe("Written warning");
    const text = JSON.stringify(letter.sections);
    expect(text).toContain("valid for 6 months, until 27 May 2027");
    expect(text).toContain("by Friday 4 December 2026");
  });

  it("warns that a final warning can lead to dismissal", () => {
    const c = { ...kase, outcome: { ...kase.outcome!, sanction: "final_written" as const } };
    const text = JSON.stringify(buildLetter("final_warning", input(c)).sections);
    expect(text).toContain("valid for 12 months");
    expect(text).toContain("may lead to dismissal");
  });

  it("includes the employee's response and the CCMA referral right on a dismissal", () => {
    const c = {
      ...kase,
      outcome: { ...kase.outcome!, sanction: "dismissal" as const, reasons: "Gross dishonesty." },
    };
    const letter = buildLetter("outcome", input(c));
    expect(letter.lead).toContain("The outcome is: dismissal.");
    const text = JSON.stringify(letter.sections);
    expect(text).toContain("I forgot to lock it.");
    expect(text).toContain("CCMA within 30 days");
  });
});
